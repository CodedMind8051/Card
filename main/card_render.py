def render_card(data: dict, layout: dict, template_path=TEMPLATE_PATH, photo_source_path=None, enhance_photo=False):
    """Compose the final card image from `data` (field values) and `layout`
    (positions/styles/photo box+crop). Returns a PIL.Image (RGB).

    Set enhance_photo=True to apply photo enhancement (upscale, denoise,
    contrast/colour/CLAHE/sharpen) to the student photo; otherwise the photo
    is used as-is."""
    if not Path(template_path).exists():
        raise FileNotFoundError(f"Template not found at {template_path}")
    im = Image.open(template_path).convert("RGB")
    draw = ImageDraw.Draw(im)

    photo_spec = layout.get("photo", {})
    crop = photo_spec.get("crop")
    if photo_source_path and crop:
        photo = load_cropped_photo(photo_source_path, crop, rotation=photo_spec.get("rotation", 0), enhance=enhance_photo)
        if photo is not None:
            px, py = int(photo_spec.get("x", PHOTO_BOX[0])), int(photo_spec.get("y", PHOTO_BOX[1]))
            pw, ph = int(photo_spec.get("width", PHOTO_BOX[2])), int(photo_spec.get("height", PHOTO_BOX[3]))
            fitted = fit_cover(photo, pw, ph)
            rounded = add_rounded_corners(fitted, radius=int(photo_spec.get("corner_radius", PHOTO_CORNER_RADIUS)))
            im.paste(rounded, (px, py), rounded)

    texts = layout.get("texts", {})

    name_spec = texts.get("student_name")
    if name_spec and name_spec.get("enabled", True):
        val = str(data.get("student_name", "") or "")
        if name_spec.get("uppercase"):
            val = val.upper()
        draw_text_box(draw, val, name_spec)

    section_spec = texts.get("section")
    if section_spec and section_spec.get("enabled", True):
        val = str(data.get("section", "") or "").strip()
        if val:
            draw_text_box(draw, section_spec.get("prefix", "") + val, section_spec)

    for key, spec in texts.items():
        if key in ("student_name", "section"):
            continue
        if spec.get("enabled", True) is False:
            continue
        val = str(data.get(key, "") or "")
        draw_text_box(draw, val, spec)

    # Extra image overlays (logos, signatures, stamps...): drawn last so they
    # sit on top of the template, photo and text, in list order.
    for spec in normalize_extra_images(layout.get("images")):
        if not spec.get("enabled", True):
            continue
        im = draw_extra_image(im, spec)

    if im.mode == "RGBA":
        im = im.convert("RGB")
    return im