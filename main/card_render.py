"""
card_render.py
---------------
Shared rendering logic for the student-ID-card pipeline.

Both the scraper (card_filler.py) and the browser editor (editor_app.py)
import from here so that the "first draft" produced by the scraper and the
image produced after you edit something in the browser are generated by the
exact same code path (no drift between preview and final export).

Everything about *where things sit on the card* (text position, font size,
colour, the photo box, photo crop/rotation) lives in a JSON-serialisable
"layout" dict. build_default_layout() creates the original hard-coded
layout as a starting point; the editor lets you change any of it and saves
the result back into the record's sidecar JSON file.
"""

